// fetch-fonts.mjs: download small subsets of Noto Serif SC and Noto Sans SC from Google Fonts,
// containing only the characters a work uses, into works/<id>/fonts/ with a fonts.css.
// Re-run after changing any text:  node tools/fetch-fonts.mjs --work=liubai
// Uses curl (which honours HTTPS_PROXY and the system CA bundle).
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const STYLE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).map(a => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));
const WORK = args.work || 'liubai', dir = resolve(STYLE_DIR, 'works', WORK), out = resolve(dir, 'fonts');

// Every non-ASCII character in the work's scripts and the shared sources, plus ASCII printable.
let text = '';
for (const d of [dir, resolve(STYLE_DIR, 'src')]) for (const f of readdirSync(d)) if (f.endsWith('.js')) text += readFileSync(resolve(d, f), 'utf8');
const chars = new Set([...text].filter(c => c.charCodeAt(0) > 126));
for (let c = 32; c < 127; c++) chars.add(String.fromCharCode(c));
const subset = [...chars].sort().join('');
console.log(`${chars.size} characters`);

const FAMILIES = [['Noto Serif SC', '400;500;600;700'], ['Noto Sans SC', '300;400;500;600;700']];
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const curl = (url, extra = []) => execFileSync('curl', ['-sSfL', '-A', UA, ...extra, url], { maxBuffer: 1 << 28 });

rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });
let css = '/* Generated by tools/fetch-fonts.mjs: subsets of Noto Serif SC / Noto Sans SC (SIL Open Font License). */\n';
for (const [family, weights] of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:wght@${weights}&text=${encodeURIComponent(subset)}&display=block`;
  const sheet = curl(url).toString();
  for (const block of sheet.split('@font-face').slice(1)) {
    const weight = block.match(/font-weight:\s*(\d+)/)[1], src = block.match(/url\((https:[^)]+)\)/)[1];
    const file = `${family.replace(/\s+/g, '')}-${weight}.woff2`;
    writeFileSync(resolve(out, file), curl(src));
    css += `@font-face { font-family: '${family}'; font-weight: ${weight}; font-display: block; src: url('${file}') format('woff2'); }\n`;
    console.log(file);
  }
}
writeFileSync(resolve(out, 'fonts.css'), css);
console.log('wrote ' + resolve(out, 'fonts.css'));
